package ecs;

/**
 * Единица логики одного тика над множеством энтити. Объявляет reads/writes —
 * контракт, на который опирается планировщик при раскладке по стадиям.
 *
 * Архетип больше НЕ называется руками (был int archetype()): система объявляет, какие компоненты
 * ей нужны, а планировщик матчит архетипы по superset. Ручное имя архетипа было привязкой к
 * фикс-диапазонам строк; component-query от физической раскладки не зависит.
 */
public interface GameSystem {
    String name();
    long reads();
    long writes();

    /**
     * Компоненты, которые архетип ОБЯЗАН иметь, чтобы система над ним работала.
     * По умолчанию — всё, что система трогает. Архетип матчится, если он superset запроса;
     * лишние компоненты у архетипа матчу не мешают.
     */
    default long query() { return reads() | writes(); }

    /** Логика для одной строки СВОЕГО архетипа. Чужие строки — только через CommandBuffer. */
    void run(View v, int row, CommandBuffer cb);
}
